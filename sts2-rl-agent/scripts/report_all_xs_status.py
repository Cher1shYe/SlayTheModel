"""Generate a consolidated status document from the frozen all-content artifacts.

Reads only checked-in evidence and runs the (safe) preflight; never trains.
"""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from sts2_env.az.all_runner import (SEARCH, VERSION, load_frozen_config, preflight,
                                    training_recipes)
from sts2_env.az.config import RULES_VERSION
from sts2_env.az.content import ALL_CONTENT
from sts2_env.az.rewards import V7

CONFIG = ROOT / 'configs' / 'az_all_xs_v1' / 'config.json'
PROTOCOL = ROOT / 'configs' / 'az_all_xs_v1' / 'protocol.json'


def _load(name):
    path = ROOT / 'docs' / name
    return json.loads(path.read_text(encoding='utf-8')) if path.exists() else None


def _sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _fmt(value, digits=3):
    return 'n/a' if value is None else f'{value:.{digits}f}'


def build():
    config = load_frozen_config(CONFIG)
    protocol = json.loads(PROTOCOL.read_text(encoding='utf-8'))
    parity = _load('all_encounter_parity.json') or {}
    robustness = _load('all_encounter_robustness.json') or {}
    generator = _load('all_deck_generator.json') or {}
    policy = _load('all_xs_policy_diagnostic.json') or {}
    budget = _load('all_xs_budget_diagnostic.json') or {}
    check = preflight(CONFIG, PROTOCOL, check_test=False)
    recipe = training_recipes(0, 1)[0]

    lines = ['# AZ All-Content Status', '']
    lines.append('Single source of truth generated by `scripts/report_all_xs_status.py`; '
                 'it reads checked-in evidence and runs the safe preflight only.')
    lines.append('')
    lines.append('## Frozen versions')
    lines.append('')
    lines.append('| Field | Value |')
    lines.append('|---|---|')
    lines.append(f'| Runner | `{VERSION}` |')
    lines.append(f'| Search | `{SEARCH}` |')
    lines.append(f'| Content | `{ALL_CONTENT}` |')
    lines.append(f'| Reward | `{V7}` |')
    lines.append(f'| Rules | `{RULES_VERSION}` |')
    lines.append(f'| Config SHA-256 | `{_sha(CONFIG)}` |')
    lines.append(f'| Protocol SHA-256 | `{_sha(PROTOCOL)}` |')
    lines.append(f"| Generator manifest SHA | `{protocol.get('generator_manifest_sha')}` |")
    lines.append(f"| Preflight manifest SHA | `{check.get('generator_manifest_sha')}` |")
    lines.append('')
    lines.append('## Frozen admission and historical generator audit')
    lines.append('')
    lines.append('| Item | Value |')
    lines.append('|---|---|')
    lines.append(f"| Encounters audited | {parity.get('encounters', 'n/a')} |")
    lines.append(f"| Parity passed | {parity.get('passed', 'n/a')} |")
    lines.append(f"| Parity sampled (hidden construction RNG) | {parity.get('sampled', 'n/a')} |")
    lines.append(f"| Parity delegated (boss contract) | {parity.get('delegated', 'n/a')} |")
    lines.append(f"| Parity failed | {parity.get('failed', 'n/a')} |")
    lines.append(f"| Robustness probes (decks x steps) | {robustness.get('decks', 'n/a')} x "
                 f"{robustness.get('steps', 'n/a')} |")
    lines.append(f"| Robust encounters | {len(robustness.get('robust') or [])}/"
                 f"{robustness.get('parity_passed', 'n/a')} |")
    lines.append(f"| Unstable encounters | {', '.join(robustness.get('unstable') or []) or 'none'} |")
    lines.append(f"| Admitted encounters | {generator.get('admitted_encounters', 'n/a')} |")
    lines.append(f"| Admitted card pool | {generator.get('admitted_pool', 'n/a')} |")
    train = (generator.get('splits') or {}).get('train', {})
    lines.append(f"| Train recipes (audited sample) | {train.get('recipes', 'n/a')} |")
    lines.append(f"| Train card coverage | {train.get('distinct_cards', 'n/a')}/"
                 f"{generator.get('admitted_pool', 'n/a')} |")
    lines.append(f"| Train encounter coverage | {train.get('distinct_encounters', 'n/a')}/"
                 f"{generator.get('admitted_encounters', 'n/a')} |")
    lines.append(f'| Example training recipe | `{recipe.scenario_id}` / `{recipe.encounter_id}` |')
    lines.append('')
    lines.append('## Split readiness (preflight)')
    lines.append('')
    lines.append('| Split | Checked | OK | Errors |')
    lines.append('|---:|---:|---:|---:|')
    lines.append(f"| Training | {check['training']['planned']} | {check['training']['ok']} | "
                 f"{len(check['training']['errors'])} |")
    lines.append(f"| Validation | {check['validation']['checked']} | {check['validation']['ok']} | "
                 f"{len(check['validation']['errors'])} |")
    lines.append('| Test | not opened | — | — |')
    lines.append(f"| ready | | | {check['ready']} |")
    lines.append('')
    audit = _load('training_readiness_mcts.json') or {}
    lines.extend(['', '## Full-horizon contract audit (no training)', '',
        f"- Completed: {len(audit.get('results', []))}/{audit.get('planned', 'n/a')}; passed: {audit.get('passed', 'n/a')}; failed: {audit.get('failed', 'n/a')}.",
        '- Opening preflight is not an end-to-end search guarantee.',
        '- Runner v2: configured value weight, 40 turns/400 decisions, update recovery, champion retention.',
        '- Historical policy/budget diagnostics below used v1 and must not be treated as v2 learning evidence.'])
    if policy:
        prior, search = policy.get('prior', {}), policy.get('search', {})
        gain = policy.get('paired_gain', {})
        lines.append('## Historical v1 initial policy diagnostic')
        lines.append('')
        lines.append('| Metric | network-only | MCTS-8 |')
        lines.append('|---|---:|---:|')
        lines.append(f"| Completed recipes | {prior.get('episodes', 'n/a')}/{policy.get('recipes')} | "
                     f"{search.get('episodes', 'n/a')}/{policy.get('recipes')} |")
        lines.append(f"| Win rate | {_fmt(prior.get('win_rate'))} | {_fmt(search.get('win_rate'))} |")
        lines.append(f"| Mean V7 utility | {_fmt(prior.get('mean_utility'))} | "
                     f"{_fmt(search.get('mean_utility'))} |")
        lines.append(f"| Decision p50 (ms) | {_fmt(1000 * prior.get('decision_seconds_p50', 0), 1)} | "
                     f"{_fmt(1000 * search.get('decision_seconds_p50', 0), 1)} |")
        lines.append(f"| Contract rejections | {prior.get('contract_rejections', 'n/a')} | "
                     f"{search.get('contract_rejections', 'n/a')} |")
        lines.append(f"| Paired gain on {gain.get('episodes', 'n/a')} common recipes | "
                     f"**{_fmt(gain.get('mean_gain'))}** ({gain.get('positive')} positive / "
                     f"{gain.get('negative')} negative / {gain.get('equal')} equal) | |")
        lines.append('')
        rejected = search.get('contract_rejected') or []
        if rejected:
            lines.append('Recorded MCTS-side rejections (not hidden):')
            lines.append('')
            lines.append('| Encounter | Error |')
            lines.append('|---|---|')
            for row in rejected:
                lines.append(f"| `{row.get('encounter')}` | {row.get('error')} |")
            lines.append('')
    if budget:
        entropy = budget.get('mean_entropy', {})
        lines.append('## Historical v1 search budget stability')
        lines.append('')
        lines.append(f"- Budgets compared: {budget.get('budgets')}")
        lines.append(f"- Decisions: {budget.get('searches')}")
        lines.append(f"- Action agreement: **{_fmt(budget.get('agreement_rate'))}**")
        lines.append(f"- Mean target entropy: {_fmt(entropy.get('small'))} (small) vs "
                     f"{_fmt(entropy.get('large'))} (large) nats")
        lines.append('')
    lines.append('## Commands')
    lines.append('')
    lines.append('```')
    lines.append('python -m sts2_env.az.all_runner --preflight-only')
    lines.append('python -m sts2_env.az.all_runner --iterations 8 --episodes 304 --updates 16 '
                 '--budget 8 --workers 2 --out output/az_all_xs_v3_stratified')
    lines.append('python scripts/summarize_all_xs_run.py output/az_all_xs_v3_stratified/report.json '
                 '--out docs/AZ_ALL_XS_RESULTS.md')
    lines.append('```')
    lines.append('')
    lines.append('## Pending decisions')
    lines.append('')
    lines.append('- Formal training authorization (see the command above).')
    lines.append('- Lifecycle, Hex restoration and interrupted-update recovery are implemented; see `AZ_TRAINING_READINESS.md`.')
    lines.append('')
    lines.append('## Honesty rules')
    lines.append('')
    lines.append('- The formal training run needs explicit authorization; nothing here starts it.')
    lines.append('- Paired gain with a CI containing 0 is not evidence of improvement.')
    lines.append('- Contract rejections are reported per encounter, never silently dropped.')
    lines.append('')
    return '\n'.join(lines)


def main():
    out = ROOT / 'docs' / 'AZ_ALL_XS_STATUS.md'
    out.write_text(build(), encoding='utf-8')
    print(out)


if __name__ == '__main__':
    main()
