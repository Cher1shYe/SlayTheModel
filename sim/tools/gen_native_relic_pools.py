"""Generate native declaration-order relic pools without filtering support.

The shared grab bag even shuffles Event/Ancient groups. Player grab bags append
the character pool, then keep Common/Uncommon/Rare/Shop only. IDs stay unchanged.
"""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=ROOT.parent / "artifacts/native-source/v0.111.0/MegaCrit/sts2/Core")
    parser.add_argument("--out", type=Path, default=ROOT / "include/sts2/native_relic_pools.inc")
    args = parser.parse_args()
    by_name = {row["name"]: row["id"] for row in json.loads((ROOT / "content/relics.json").read_text())}
    lines = ["// Generated by tools/gen_native_relic_pools.py from v0.111.0 native pools.",
             "// Declaration order controls dictionary grouping and UpFront draws."]
    for name in ("Shared", "Ironclad"):
        source = (args.source / "Models/RelicPools" / (name + "RelicPool.cs")).read_text()
        declaration = source.split("GenerateAllRelics()", 1)[1].split("public override IEnumerable<RelicModel> GetUnlockedRelics", 1)[0]
        models = re.findall(r"ModelDb\.Relic<(\w+)>\(\)", declaration)
        declared_count = re.search(r"new RelicModel\[(\d+)\]", declaration)
        if not declared_count or len(models) != int(declared_count.group(1)) or len(set(models)) != len(models):
            raise ValueError(f"{name}: unsupported native pool declaration")
        lines.append(f"constexpr RelicId NATIVE_{name.upper()}_RELICS[] = {{")
        lines.extend(f"    RelicId::{by_name[model]}," for model in models)
        lines.append("};")
    args.out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
