"""Generate relics_generated.inc from relics.json."""
from __future__ import annotations

import argparse
import json


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    rows = json.load(open(args.json, encoding="utf-8"))
    rarity = {0: "Rarity::SPECIAL", 1: "Rarity::COMMON", 2: "Rarity::UNCOMMON",
              3: "Rarity::RARE", 4: "Rarity::SPECIAL", 5: "Rarity::SPECIAL",
              6: "Rarity::SPECIAL", 7: "Rarity::SPECIAL"}
    pool = {"SHARED": "RelicPool::SHARED", "IRONCLAD": "RelicPool::IRONCLAD",
            "EVENT": "RelicPool::EVENT", "FALLBACK": "RelicPool::OTHER",
            "DEPRECATED": "RelicPool::OTHER", "SILENT": "RelicPool::OTHER",
            "DEFECT": "RelicPool::OTHER", "REGENT": "RelicPool::OTHER",
            "NECROBINDER": "RelicPool::OTHER"}

    lines = ["// Generated by gen_relics.py from content/relics.json. Do not edit.",
             "#ifdef STS2_RELIC_CONTENT_ENUMS",
             "enum class RelicId : std::uint16_t {", "    INVALID = 0,"]
    for r in rows:
        lines.append(f"    {r['id']},")
    lines += ["    COUNT", "};", "#else", "",
              "static const RelicDef RELIC_DEFS[] = {",
              '    {RelicId::INVALID, "", "", Rarity::SPECIAL, RelicPool::OTHER, false},']
    for r in rows:
        lines.append(
            f'    {{RelicId::{r["id"]}, "{r["id"]}", "{r["name"]}", '
            f'{rarity[r["rarity"]]}, {pool[r["pool"]]}, false}},')
    lines += ["};", "",
              "static_assert(sizeof(RELIC_DEFS) / sizeof(RELIC_DEFS[0]) == static_cast<int>(RelicId::COUNT), \"relic table size\");",
              "#endif", ""]
    open(args.out, "w", encoding="utf-8").write("\n".join(lines))
    print(f"wrote {len(rows)} relics")


if __name__ == "__main__":
    main()
