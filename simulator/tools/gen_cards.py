"""Generate C++ CardId / VarId enums and the CardDef table from cards.json.

    python simulator/tools/gen_cards.py

The generated file is included twice by common.h / cards.cpp behind
STS2_CARD_CONTENT_ENUMS so the enums exist before CardDef and the table after.
"""
from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "content" / "cards.json"
OUT = ROOT / "include" / "sts2" / "cards_generated.inc"

TYPES = {"ATTACK": "ATTACK", "SKILL": "SKILL", "POWER": "POWER",
         "STATUS": "STATUS", "CURSE": "CURSE"}
TARGETS = {"ANY_ENEMY": "ENEMY", "ALL_ENEMIES": "ALL_ENEMIES", "SELF": "SELF",
           "RANDOM_ENEMY": "RANDOM_ENEMY", "ANY_ALLY": "ALLY",
           "ALL_ALLIES": "ALL_ALLIES", "NONE": "NONE"}
RARITIES = {"BASIC": "BASIC", "COMMON": "COMMON", "UNCOMMON": "UNCOMMON",
            "RARE": "RARE", "SPECIAL": "SPECIAL", "ANCIENT": "ANCIENT",
            "STATUS": "SPECIAL", "CURSE": "SPECIAL", "TOKEN": "SPECIAL"}


def cstr(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    cards = json.loads(SRC.read_text(encoding="utf-8"))
    var_keys = sorted({k for c in cards for k in c["effect_vars"]}
                      | {k for c in cards for k in c["variants"]["upgraded"]["effect_vars"]})
    var_id = {k: k.upper() for k in var_keys}
    for name in var_id.values():
        assert name.replace("_", "").isalnum(), name

    lines = ["// generated by simulator/tools/gen_cards.py -- do not edit", ""]
    lines.append("#ifdef STS2_CARD_CONTENT_ENUMS")
    lines.append("enum class CardId : std::uint16_t {")
    lines.append("    INVALID = 0,")
    for c in cards:
        lines.append(f"    {c['id']},")
    lines.append("    COUNT")
    lines.append("};")
    lines.append("")
    lines.append("enum class VarId : std::uint8_t {")
    for k in var_keys:
        lines.append(f"    {var_id[k]},")
    lines.append("    COUNT")
    lines.append("};")
    lines.append("#else")
    lines.append("// clang-format off")
    lines.append("constexpr CardDef CARD_DEFS[] = {")
    lines.append("    {CardId::INVALID, \"\", \"\", 0, 0, CardType::SKILL, TargetType::SELF,"
                 " Rarity::SPECIAL, 0, 0, 0, 0, {}, {}, 0},")
    for c in cards:
        up = c["variants"]["upgraded"]
        def flags(v):
            f = 0
            fl = v["flags"] if "flags" in v else {"exhausts": "exhaust" in v["keywords"],
                                                  "ethereal": "ethereal" in v["keywords"],
                                                  "innate": "innate" in v["keywords"],
                                                  "retain": "retain" in v["keywords"],
                                                  "unplayable": "unplayable" in v["keywords"]}
            if fl["ethereal"]: f |= 1
            if fl["exhausts"]: f |= 2
            if fl["innate"]: f |= 4
            if fl["retain"]: f |= 8
            if fl["unplayable"]: f |= 16
            if "STRIKE" in c.get("tags", []): f |= 32
            if "DEFEND" in c.get("tags", []): f |= 64
            if c.get("multiplayer_only"): f |= 128
            return f
        base_vars = [str(int(c["effect_vars"].get(k, 0))) for k in var_keys]
        up_vars = [str(int(up["effect_vars"].get(k, 0))) for k in var_keys]
        title = c["title"] or c["id"]
        cost = -1 if c.get("x_cost") else c["cost"]
        cost_up = -1 if up.get("x_cost") else up["cost"]
        lines.append(
            "    {CardId::%s, %s, %s, %d, %d, CardType::%s, TargetType::%s, Rarity::%s, "
            "%d, %d, %d, %d, {%s}, {%s}, %d}," % (
                c["id"], cstr(c["id"]), cstr(title), cost, cost_up,
                TYPES.get(c["type"], "SKILL"), TARGETS.get(c["target"], "SELF"),
                RARITIES.get(c["rarity"], "SPECIAL"),
                c["base_damage"] or 0, up["base_damage"] or 0,
                c["base_block"] or 0, up["base_block"] or 0,
                ", ".join(base_vars), ", ".join(up_vars), flags(c["variants"]["base"])))
    lines.append("};")
    lines.append("static_assert(sizeof(CARD_DEFS) / sizeof(CARD_DEFS[0]) =="
                 " static_cast<int>(CardId::COUNT), \"card table size\");")
    lines.append("#endif")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(cards)} cards, {len(var_keys)} vars)")


if __name__ == "__main__":
    main()
