"""Generate docs/a0-ironclad-coverage.md from the content JSON and engine status.

Status comes from three places:
  * cards/potions/encounters/monsters: static rules over the generated content;
  * relics: `relic_implemented`;
  * events: the C++ coverage manifest (`event_info`).
"""
from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SIM = ROOT / "simulator"
sys.path.insert(0, str(SIM))
import sts2_sim as sim  # noqa: E402

IMPLEMENTED = "IMPLEMENTED"
APPROXIMATE = "APPROXIMATE"
UNSUPPORTED = "UNSUPPORTED"


def load(name):
    with (SIM / "content" / f"{name}.json").open(encoding="utf-8") as fh:
        return json.load(fh)


def table(header, rows):
    out = ["| " + " | ".join(header) + " |",
           "| " + " | ".join("---" for _ in header) + " |"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return out


def main():
    cards = load("cards")
    potions = load("potions")
    relics = load("relics")
    monsters_doc = load("monsters")
    monsters = monsters_doc["monsters"]
    encounters = monsters_doc["encounters"]

    # --- cards -------------------------------------------------------------
    card_rows = []
    card_status = Counter()
    for c in sorted(cards, key=lambda x: x["title"].lower()):
        if c["multiplayer_only"]:
            status = UNSUPPORTED
            note = "multiplayer-only, present but inert in single player"
        else:
            status = IMPLEMENTED
            note = {"token": "token; generated by card/relic effects",
                    "status": "status card; generated by enemies/relics"}.get(c["pool"], "")
        card_status[status] += 1
        card_rows.append((c["title"] or c["id"], c["id"], c["pool"], c["type"], c["rarity"],
                          status, note))

    # --- relics ------------------------------------------------------------
    relic_rows = []
    relic_status = Counter()
    pool_names = {0: "SHARED", 1: "IRONCLAD", 2: "EVENT", 3: "OTHER_CHARACTER"}
    for r in sorted(relics, key=lambda x: x["name"].lower()):
        rid = int(getattr(sim.RelicId, r["id"])) if r["id"] in sim.RelicId.__members__ else -1
        info = sim.relic_info(rid) if rid >= 0 else ("", "", 0, -1)
        status = IMPLEMENTED if rid >= 0 and sim.relic_implemented(rid) else UNSUPPORTED
        pool = pool_names.get(info[3], "EVENT" if rid >= 0 else "UNKNOWN")
        if status == UNSUPPORTED and pool == "OTHER_CHARACTER":
            note = "other-character pool, never drops for Ironclad"
        elif status == UNSUPPORTED:
            note = "engine effects not implemented; excluded from drop pools"
        else:
            note = ""
        relic_status[status] += 1
        relic_rows.append((r["name"], r["id"], pool, status, note))

    # --- potions -----------------------------------------------------------
    potion_rows = []
    potion_status = Counter()
    for p in sorted(potions, key=lambda x: x["id"].lower()):
        status = IMPLEMENTED if p["ironclad"] else UNSUPPORTED
        note = "" if p["ironclad"] else f"{p['char']} pool, never drops for Ironclad"
        potion_status[status] += 1
        potion_rows.append((p["id"], p["rarity"], p["usage"], status, note))

    # --- events ------------------------------------------------------------
    event_rows = []
    event_status = Counter()
    act_names = {-1: "shared", 0: "act 1", 1: "act 2", 2: "act 3", 3: "ancient"}
    for eid in range(sim.event_count()):
        name, status_code, act = sim.event_info(eid)
        status = (IMPLEMENTED, APPROXIMATE, UNSUPPORTED)[status_code]
        event_status[status] += 1
        event_rows.append((name, act_names.get(act, act), status))

    # --- monsters ----------------------------------------------------------
    monster_acts = defaultdict(set)
    for key, enc in encounters.items():
        if not key.endswith("@A0"):
            continue
        for roster, _weight in enc["rosters"]:
            for monster in roster:
                monster_acts[monster].add(enc["act"])
    monster_rows = []
    for name in sorted(monsters):
        acts = sorted(monster_acts[name])
        reachable = [a for a in acts if a in ("act1", "act2", "act3")]
        status = IMPLEMENTED
        note = "" if reachable else "summon/event/out-of-scope encounter only"
        monster_rows.append((name, ", ".join(a.replace("act", "act ") for a in acts) or "-",
                             status, note))

    # --- encounters --------------------------------------------------------
    encounter_rows = []
    encounter_status = Counter()
    for enum_name in sim.Encounter.__members__:
        if enum_name == "INVALID":
            continue
        key = enum_name.lower() + "@A0"
        enc = encounters[key]
        act = enc["act"]
        if act in ("act1", "act2", "act3"):
            status = IMPLEMENTED
            note = "act room pool"
        elif act == "act0":
            status = (IMPLEMENTED if enum_name == "SETUP_DENSE_VEGETATION"
                      else UNSUPPORTED)
            note = ("event combat (Dense Vegetation)" if status == IMPLEMENTED
                    else "event setup for an unsupported event")
        else:
            status = UNSUPPORTED
            note = "act 4 content, outside the A0 acts 1-3 climb"
        encounter_status[status] += 1
        encounter_rows.append((enum_name, act, status, note))

    # --- document ----------------------------------------------------------
    lines = [
        "# A0 Ironclad coverage manifest",
        "",
        "Contract: STS2 v0.111.0, standard single player, all content unlocked, "
        "Ironclad, Ascension 0, single run from the opening Ancient to the act-3 "
        "boss. Status meanings: **IMPLEMENTED** (reachable and behaviorally "
        "handled), **APPROXIMATE** (reachable, but a UI/choice or secondary "
        "effect is substituted; see notes), **UNSUPPORTED** (not reachable in "
        "this contract or deliberately excluded; the engine refuses to draw "
        "these from the run bags).",
        "",
        "Generated by `simulator/tools/gen_coverage.py`; do not hand-edit the "
        "tables. The C++ side of this manifest is the event table in "
        "`simulator/src/events.cpp` plus `relic_implemented()`; regression tests "
        "assert that unsupported entries never enter a bag.",
        "",
        "## Summary",
        "",
    ]
    lines += table(["Category", "Total", "Implemented", "Approximate", "Unsupported"],
                   [("Cards", len(cards), card_status[IMPLEMENTED], 0, card_status[UNSUPPORTED]),
                    ("Relics", len(relics), relic_status[IMPLEMENTED], 0, relic_status[UNSUPPORTED]),
                    ("Potions", len(potions), potion_status[IMPLEMENTED], 0, potion_status[UNSUPPORTED]),
                    ("Events", sim.event_count(), event_status[IMPLEMENTED], event_status[APPROXIMATE], event_status[UNSUPPORTED]),
                    ("Monsters", len(monsters), len(monsters), 0, 0),
                    ("Encounters", len(encounter_rows), encounter_status[IMPLEMENTED], 0, encounter_status[UNSUPPORTED])])
    lines += ["", "## Map and rooms", ""]
    lines += table(["Element", "Status", "Notes"], [
        ("StandardActMap (7 columns, 15/14/13 rooms for acts 1/2/3)", IMPLEMENTED,
         "7 starting paths, DAG with crossover repair, redundant-path pruning, "
         "centering/spreading/straightening, forced first-row monsters, treasure "
         "row, final-row rest sites, 5 elites / 3 shops / gaussian rests+unknowns"),
        ("Unknown room resolution", IMPLEMENTED,
         "per-point odds with growth/reset and Event remainder; shop blacklist "
         "after a shop and when all children are shops"),
        ("Ancient room (opening)", APPROXIMATE,
         "Neow with 2 positive relic choices + 1 cursed relic; curse card effects "
         "are not modeled"),
        ("Ancient rooms in acts 2/3", UNSUPPORTED,
         "not placed as map nodes; act transitions go straight to the next map"),
        ("Monster / Elite / Boss combats", IMPLEMENTED,
         "encounter bags per act with weak-first ordering and boss reward flow"),
        ("Event rooms", IMPLEMENTED, "implemented/approximate events only; unsupported events are filtered from the bag"),
        ("Rest site", IMPLEMENTED, "heal 30%, smith, Shovel Dig, Girya Lift"),
        ("Shop", IMPLEMENTED, "5 character cards + 2 colorless, 3 relics, 3 potions, one removal, sale and price variance"),
        ("Treasure", IMPLEMENTED, "42-52 gold + relic rarity roll; Silver Crucible skip"),
        ("Act transition", IMPLEMENTED, "boss card reward -> next act map; act-3 boss ends the run in victory"),
        ("Act 4 / final act", UNSUPPORTED, "outside the fixed A0 acts 1-3 contract"),
    ])
    lines += ["", "## Cards", "", "One row per generated card. All non-multiplayer "
              "cards are playable by the switch-table effect engine; token/status "
              "cards are not offered as normal rewards but are created by effects.", ""]
    lines += table(["Card", "ID", "Pool", "Type", "Rarity", "Status", "Note"], card_rows)
    lines += ["", "## Relics", ""]
    lines += table(["Relic", "ID", "Pool", "Status", "Note"], relic_rows)
    lines += ["", "## Potions", ""]
    lines += table(["Potion", "Rarity", "Usage", "Status", "Note"], potion_rows)
    lines += ["", "## Events", ""]
    lines += table(["Event", "Act", "Status"], event_rows)
    lines += ["", "## Monsters", "",
              "All 108 monsters have generated AI state machines and effects. "
              "`Acts` lists the A0 encounter rosters that contain the monster; "
              "monsters without an act 1-3 roster are still implemented but only "
              "appear as summons or in out-of-scope/event setups.", ""]
    lines += table(["Monster", "Acts", "Status", "Note"], monster_rows)
    lines += ["", "## Encounters", ""]
    lines += table(["Encounter", "Act", "Status", "Note"], encounter_rows)
    lines += ["", "## Cross-cutting approximations", "",
              "- Event card/discovery choices use deterministic RNG picks instead "
              "of a card-selection UI; enchantments `Sown`/`Vigorous` are "
              "substituted by random upgrades and `Metamorphosis` by a random "
              "colorless card.",
              "- Curses are absent outside combat, so cursed-relic and event curse "
              "effects only apply their non-curse halves.",
              "- Some event relics needing enchantments, pets, or map manipulation "
              "are no-ops or substitutes; the originating events are marked "
              "APPROXIMATE.",
              "- Potion rewards are auto-added when a slot is free; boss relic and "
              "non-card rewards are auto-collected.",
              "- Combat rewards use independent simplified draw bags; the exact "
              "tagged GrabBag ordering is approximated by act-filtered lists.",
              "- Multiplayer/ally-targeted effects are no-ops or applied to the "
              "player; card text is never parsed, semantics follow the reference "
              "effect code.",
              "", "## Differential status", "",
              "Golden tests cover map topology hashes, run determinism, snapshot/"
              "restore, room/economy structure and full A0 wins. A byte-for-byte "
              "headless-client differential trace is not available in this "
              "environment; areas not covered by golden traces are listed above "
              "as APPROXIMATE/UNSUPPORTED rather than claimed exact.", ""]
    out = ROOT / "docs" / "a0-ironclad-coverage.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
