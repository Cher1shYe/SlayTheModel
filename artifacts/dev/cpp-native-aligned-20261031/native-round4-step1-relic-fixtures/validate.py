"""Validate target-DLL fixtures and export their ordered C++ expectations."""
from pathlib import Path
import hashlib
import json

here = Path(__file__).resolve().parent
result = json.loads((here / "results.json").read_text())
expected_hash = "9cb4f1ad8c9f284aa8fec3122ffd6d780bbf543d875c817abdd12ff63fbf12b4"
assert result["status"] == "completed"
assert result["gameAssemblySha256"] == expected_hash
cases = {case["test"]: case for case in result["results"]}
assert len(cases) == 11
refinement = {
    "BURNING_BLOOD": "BLACK_BLOOD", "BLACK_BLOOD": "CIRCLET",
    "RING_OF_THE_SNAKE": "RING_OF_THE_DRAKE", "CRACKED_CORE": "INFUSED_CORE",
    "BOUND_PHYLACTERY": "PHYLACTERY_UNBOUND", "DIVINE_RIGHT": "DIVINE_DESTINY",
}
fixture_rows = []
for name, case in cases.items():
    if "nicheCounter" not in case:
        continue
    assert case["setup"] and case["originalRemoved"] and case["replacementIsFresh"] and case["siblingIdentityPreserved"]
    assert case["nicheCounter"] == 0
    assert case["upgraded"] == refinement[case["starter"]]
    before, after = case["before"], case["after"]
    replacement_index = next(i for i, relic in enumerate(before) if relic["id"] == case["starter"])
    assert len(before) == 4 and len(after) == 5 and after[-1]["id"] == "TOUCH_OF_OROBAS"
    for i, relic in enumerate(before):
        if i == replacement_index:
            assert after[i]["id"] == case["upgraded"] and after[i]["floor"] == 1
            assert after[i]["counter"] == 0 and not after[i]["wax"]
        else:
            assert after[i] == relic
    assert [(event["action"], event["id"]) for event in case["events"]] == [
        ("obtain", "TOUCH_OF_OROBAS"), ("remove", case["starter"]), ("obtain", case["upgraded"])]
    assert case["events"][-1]["order"] == [relic["id"] for relic in after]
    def ids(items):
        return "{" + ",".join("RelicId::" + relic["id"] for relic in items) + "}"
    def counters(items):
        return "{" + ",".join(str(relic["counter"]) for relic in items) + "}"
    fixture_rows.append('    {"' + name + '",' + ids(before) + ',' + counters(before) + ',' + ids(after) + ',' + counters(after) + '},')
assert len(fixture_rows) == 8
first = cases["first_starter_wins"]
assert first["starter"] == "BLACK_BLOOD" and first["upgraded"] == "CIRCLET"
assert [x["id"] for x in first["after"]] == ["PEN_NIB", "CIRCLET", "BURNING_BLOOD", "TOUCH_OF_OROBAS"]
hook = cases["replacement_after_obtained_hook"]
assert (hook["hpBefore"],hook["maxHpBefore"],hook["hp"],hook["maxHp"]) == (30,80,37,87)
assert hook["after"][1]["id"] == "STRAWBERRY" and hook["originalRemoved"]
missing = cases["no_starter"]
assert not missing["setup"] and missing["error"] == "System.InvalidOperationException"
assert [r["id"] for r in missing["after"]] == ["PEN_NIB", "TOUCH_OF_OROBAS"]
(here / "replacement_cases.inc").write_text(
    "// Generated by validate.py from the target DLL results.json.\n"
    "const NativeRelicReplacementCase nativeReplacementCases[] = {\n" + "\n".join(fixture_rows) + "\n};\n")
report = {
    "status": "passed", "fixture_count": len(cases), "ordered_replacement_fixtures": len(fixture_rows),
    "game_assembly_sha256": expected_hash,
    "results_sha256": hashlib.sha256((here / "results.json").read_bytes()).hexdigest(),
    "scope": "Touch starter mapping, original position, native object/counter persistence, acquisition callback, missing-starter eligibility. C++ wax/floor metadata and other-character mechanics are not claimed supported.",
    "invalid_call_boundary": "Native SetupForPlayer returns false; forced invalid Obtain inserts then throws. Simulator rejects the unsupported obtain atomically before mutation.",
}
(here / "validation.json").write_text(json.dumps(report, indent=2) + "\n")
print(json.dumps(report, indent=2))
