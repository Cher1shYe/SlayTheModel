"""Generate the original game relic-rarity lookup from content/relics.json."""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def render(rows: list[dict]) -> str:
    # Ancient was recorded as 7 by the collector; None relics were recorded as
    # common. Expose the collector values and distinguish None as -1.
    names = {0: "STARTER", 1: "COMMON", 2: "UNCOMMON", 3: "RARE",
             4: "SHOP", 5: "EVENT", 7: "ANCIENT"}
    none_ids = {"CIRCLET", "DEPRECATED_RELIC"}
    lines = ["// Generated by gen_relic_raw_rarity.py; do not edit.",
             "#pragma once", "", '#include "sts2/common.h"', "",
             "namespace sts2 {", "", "enum class RelicRawRarity : int {",
             "    NONE = -1, STARTER = 0, COMMON = 1, UNCOMMON = 2, RARE = 3,",
             "    SHOP = 4, EVENT = 5, ANCIENT = 7",
             "};", "", "constexpr int relic_raw_rarity(RelicId id) {", "    switch (id) {"]
    for row in rows:
        rarity = "NONE" if row["id"] in none_ids else names[row["rarity"]]
        lines.append(f'        case RelicId::{row["id"]}: return static_cast<int>(RelicRawRarity::{rarity});')
    lines += ["        default: return static_cast<int>(RelicRawRarity::NONE);", "    }", "}", "", "}  // namespace sts2", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--json", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()
    rows = json.loads(args.json.read_text(encoding="utf-8"))
    args.out.write_text(render(rows), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
