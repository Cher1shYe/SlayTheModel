"""Generate include/sts2/epoch_unlocks.inc from the v0.111.0 native source.

    python simulator/tools/gen_epoch_unlocks.py <native Core dir>

For every card/relic/potion pool whose GetUnlocked* / FilterThroughEpochs
checks IsEpochRevealed<XEpoch>(), the content listed in XEpoch.Cards /
Relics / Potions is locked until that epoch is revealed. Epoch bit order is
the sorted epoch class list (stable; appended epochs would go at the end).
"""
from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "include" / "sts2" / "epoch_unlocks.inc"


def snake(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    s = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", s)
    return s.upper()


def main() -> None:
    core = pathlib.Path(sys.argv[1])
    epochs = sorted(p.stem for p in (core / "Timeline" / "Epochs").glob("*Epoch.cs"))
    bit = {e: i for i, e in enumerate(epochs)}
    if len(epochs) > 64:
        raise SystemExit("epoch mask exceeds 64 bits")
    kinds = {"Card": "CardPools", "Relic": "RelicPools", "Potion": "PotionPools"}
    locked = {k: {} for k in kinds}
    for kind, folder in kinds.items():
        for pool in sorted((core / "Models" / folder).glob("*.cs")):
            for epoch in re.findall(r"IsEpochRevealed<(\w+)>", pool.read_text(encoding="utf-8")):
                text = (core / "Timeline" / "Epochs" / f"{epoch}.cs").read_text(encoding="utf-8")
                section = re.search(rf"List<{kind}Model> {kind}s\b(.*?)return list;", text, re.S)
                if not section:
                    raise SystemExit(f"{epoch} has no {kind}s list but {pool.name} checks it")
                for name in re.findall(rf"ModelDb\.{kind}<(\w+)>\(\)", section.group(1)):
                    locked[kind].setdefault(name, epoch)
    lines = ["// generated by simulator/tools/gen_epoch_unlocks.py -- do not edit", ""]
    lines.append(f"constexpr int NATIVE_EPOCH_COUNT = {len(epochs)};")
    lines.append("static const char *const NATIVE_EPOCH_NAMES[] = {")
    lines += [f'    "{e}",' for e in epochs]
    lines.append("};")
    # C++ card keys that differ from the snake-cased class name (macro/power
    # name clashes); potion keys are the native class names themselves.
    rename = {"Card": {"Null": "NULL_CARD", "Sloth": "SLOTH_STATUS", "Calamity": "CALAMITY_CARD",
                       "Cruelty": "CRUELTY_CARD", "DrumOfBattle": "DRUM_OF_BATTLE_CARD",
                       "Inferno": "INFERNO_CARD", "Nostalgia": "NOSTALGIA_CARD"},
              "Relic": {}, "Potion": {}}
    for kind in kinds:
        lines.append(f"struct Native{kind}EpochLock {{ const char *key; std::uint8_t epoch; }};")
        lines.append(f"static const Native{kind}EpochLock NATIVE_{kind.upper()}_EPOCH_LOCKS[] = {{")
        for name, epoch in sorted(locked[kind].items()):
            key = rename[kind].get(name, name if kind == "Potion" else snake(name))
            lines.append(f'    {{"{key}", {bit[epoch]}}},  // {name} <- {epoch}')
        lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}: {len(epochs)} epochs, " + ", ".join(f"{len(v)} {k.lower()}s" for k, v in locked.items()))


if __name__ == "__main__":
    main()
