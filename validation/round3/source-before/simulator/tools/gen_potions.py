"""Generate potions_generated.inc from potions.json."""
from __future__ import annotations

import argparse
import json
import re


def snake(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    return s.upper()


def display(name: str) -> str:
    return re.sub(r"(?<=[a-z])(?=[A-Z])", " ", name)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    rows = json.load(open(args.json, encoding="utf-8"))
    rarity = {0: "Rarity::COMMON", 1: "Rarity::UNCOMMON", 2: "Rarity::RARE",
              3: "Rarity::SPECIAL", 4: "Rarity::SPECIAL", 5: "Rarity::SPECIAL"}
    usage = {0: "PotionUsage::COMBAT_ONLY", 1: "PotionUsage::ANY_TIME",
             2: "PotionUsage::AUTOMATIC"}
    target = {0: "PotionTarget::SELF", 1: "PotionTarget::ANY_ENEMY",
              2: "PotionTarget::ALL_ENEMIES", 3: "PotionTarget::ANY_PLAYER"}

    lines = ["// Generated by gen_potions.py from content/potions.json. Do not edit.",
             "#ifdef STS2_POTION_CONTENT_ENUMS",
             "enum PotionId : std::uint8_t {", "    INVALID = 0,"]
    for r in rows:
        lines.append(f"    {snake(r['id'])},")
    lines += ["    COUNT", "};", "#else", "",
              "static const PotionDef POTION_DEFS[] = {"]
    lines.append('    {PotionId::INVALID, "", "", Rarity::COMMON, PotionUsage::COMBAT_ONLY, PotionTarget::SELF, false, false},')
    for r in rows:
        lines.append(
            f'    {{PotionId::{snake(r["id"])}, "{r["id"]}", "{display(r["id"])}", '
            f'{rarity[r["rarity"]]}, {usage[r["usage"]]}, {target[r["target"]]}, '
            f'{"true" if r["ironclad"] else "false"}, '
            f'{"true" if r["combatGen"] else "false"}}},')
    lines += ["};", "",
              f"static_assert(sizeof(POTION_DEFS) / sizeof(POTION_DEFS[0]) == static_cast<int>(PotionId::COUNT), \"potion table size\");",
              "#endif", ""]
    open(args.out, "w", encoding="utf-8").write("\n".join(lines))
    print(f"wrote {len(rows)} potions")


if __name__ == "__main__":
    main()
